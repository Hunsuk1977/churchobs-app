#!/usr/bin/env python3
"""scripts/translations_en.py → app/resources/en.lproj/Localizable.strings (+ 빈 ko.lproj)"""
from pathlib import Path
import importlib.util
root = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('t', root / 'scripts/translations_en.py'); mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
def esc(s):  # 원문에 이미 \n 같은 이스케이프가 들어 있으므로 따옴표만 처리
    return s.replace('"', '\\"')
lines = ['/* Church OBS English. Generated by scripts/make_strings.py — edit translations_en.py */']
for k, v in mod.T.items():
    lines.append(f'"{esc(k)}" = "{esc(v)}";')
(root / 'app/resources/en.lproj').mkdir(parents=True, exist_ok=True)
(root / 'app/resources/en.lproj/Localizable.strings').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(root / 'app/resources/ko.lproj').mkdir(parents=True, exist_ok=True)
(root / 'app/resources/ko.lproj/Localizable.strings').write_text('/* 한국어는 원문 그대로 사용 */\n', encoding='utf-8')
(root / 'app/resources/en.lproj/InfoPlist.strings').write_text(
    '"CFBundleDisplayName" = "Church OBS";\n'
    '"NSCameraUsageDescription" = "Church OBS uses the camera for the service preview, recording and streaming.";\n'
    '"NSMicrophoneUsageDescription" = "Church OBS uses the selected microphone to record and stream service audio.";\n', encoding='utf-8')
print('strings', len(mod.T))
